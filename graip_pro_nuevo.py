# 0. CATÁLOGO DE GRAPHLETS Y TABLA DE BÚSQUEDA (Sect. 3.2 del paper)
#    Cada subgrafo de k nodos se codifica como una máscara de bits
#    (un bit por par de nodos) y se identifica con una tabla precalculada.
# =====================================================================
_NOMBRES_4 = {
    (1, 1, 1, 3): "Estrella (K1,3)",
    (1, 1, 2, 2): "Camino (P4)",
    (2, 2, 2, 2): "Ciclo (C4)",
    (1, 2, 2, 3): "Paleta (paw)",
    (2, 2, 3, 3): "Diamante",
    (3, 3, 3, 3): "Completo (K4)",
}


def catalogo_graphlets(ng):
    """
    Construye el catálogo de graphlets de 3..ng nodos y la tabla
    (k, máscara) -> índice global del graphlet (-1 si el subgrafo no es conexo).
    Los índices son ÚNICOS entre órdenes: primero los de 3 nodos, luego los de 4, etc.
    Dentro de cada orden van de menor a mayor número de aristas (M1 = cuña, M2 = triángulo).
    """
    pares = {k: list(itertools.combinations(range(k), 2)) for k in range(2, ng + 1)}
    tabla = {}
    nombres = []
    ordenes = []
    total = 0
    for k in range(3, ng + 1):
        P = pares[k]
        reps_k = []  # (indice_global, grafo representante)
        mascaras = sorted(range(1 << len(P)), key=lambda x: (bin(x).count("1"), x))
        for mask in mascaras:
            g = nx.Graph()
            g.add_nodes_from(range(k))
            g.add_edges_from(P[b] for b in range(len(P)) if (mask >> b) & 1)
            if not nx.is_connected(g):
                tabla[(k, mask)] = -1
                continue
            idx = -1
            for j, rep in reps_k:
                if rep.number_of_edges() == g.number_of_edges() and nx.is_isomorphic(rep, g):
                    idx = j
                    break
            if idx == -1:
                idx = total
                total += 1
                reps_k.append((idx, g))
                ordenes.append(k)
                grados = tuple(sorted(d for _, d in g.degree()))
                if k == 3:
                    nombre = "Cuña (P3)" if g.number_of_edges() == 2 else "Triángulo (K3)"
                elif k == 4:
                    nombre = _NOMBRES_4[grados]
                else:
                    nombre = f"{k} nodos, {g.number_of_edges()} aristas"
                nombres.append(nombre)
            tabla[(k, mask)] = idx
    return {"ng": ng, "pares": pares, "tabla": tabla, "nombres": nombres,
            "ordenes": ordenes, "n_tipos": total}


def mascara(G, nodos, cat):
    """Máscara de bits del subgrafo inducido por 'nodos' (en ese orden)."""
    k = len(nodos)
    m = 0
    for b, (i, j) in enumerate(cat["pares"][k]):
        if G.has_edge(nodos[i], nodos[j]):
            m |= 1 << b
    return m


def conjuntos_conexos(G, semilla, kmax, permitido=None):
    """
    Todos los conjuntos de nodos que inducen un subgrafo conexo en G, de tamaño <= kmax,
    y que contienen el conjunto 'semilla' (que debe ser conexo en G).
    Sólo explora el vecindario local de la semilla (como en el paper).
    """
    inicio = frozenset(semilla)
    vistos = {inicio}
    frontera = [inicio]
    while frontera:
        siguiente = []
        for C in frontera:
            if len(C) >= kmax:
                continue
            vecinos = set()
            for x in C:
                vecinos.update(G.adj[x])
            vecinos -= C
            for y in vecinos:
                if permitido is not None and not permitido(y):
                    continue
                D = C | {y}
                if D not in vistos:
                    vistos.add(D)
                    siguiente.append(D)
        frontera = siguiente
    return vistos


def contar_graphlets(G, cat):
    """Conteo exacto de todos los graphlets (subgrafos inducidos conexos) de 3..ng nodos."""
    C = np.zeros(cat["n_tipos"], dtype=np.int64)
    rango = {v: i for i, v in enumerate(G.nodes())}
    for v in G.nodes():
        rv = rango[v]
        # cada conjunto se cuenta una sola vez: desde su nodo de menor rango
        for conj in conjuntos_conexos(G, {v}, cat["ng"], permitido=lambda y: rango[y] > rv):
            if len(conj) >= 3:
                C[cat["tabla"][(len(conj), mascara(G, list(conj), cat))]] += 1
    return C


def contar_graphlets_fuerza_bruta(G, cat):
    """Conteo por fuerza bruta (sólo para verificar en grafos chicos)."""
    C = np.zeros(cat["n_tipos"], dtype=np.int64)
    for k in range(3, cat["ng"] + 1):
        for comb in itertools.combinations(G.nodes(), k):
            idx = cat["tabla"][(k, mascara(G, list(comb), cat))]
            if idx >= 0:
                C[idx] += 1
    return C


