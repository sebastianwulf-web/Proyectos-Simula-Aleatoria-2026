# 4. FUNCIÓN SAMPLE (Monte Carlo sobre la red probabilística)
# =====================================================================
def Sample(G, S, ng=3, seed=None, guardar_muestras=False):
    """
    Genera S grafos posibles de G (cada arista con probabilidad 'prob'; los nodos
    también pueden tener 'prob', por defecto 1), toma la COMPONENTE CONEXA MAYOR de cada
    muestra (como en el paper) y calcula En, sn, Em, sm, EN, sN, Ec, sc.
    """
    rng = np.random.default_rng(seed)
    cat = catalogo_graphlets(ng)
    nodos = list(G.nodes())
    aristas = list(G.edges())
    p_nodo = np.array([G.nodes[x].get("prob", 1.0) for x in nodos], dtype=float)
    p_arista = np.array([G[a][b].get("prob", 1.0) for a, b in aristas], dtype=float)
    nmax = len(nodos)

    n_s, m_s, hist_s, gl_s, GS = [], [], [], [], []
    for _ in range(S):
        vivo = rng.random(nmax) < p_nodo
        vivos = {x for x, ok in zip(nodos, vivo) if ok}
        sel = rng.random(len(aristas)) < p_arista
        Gi = nx.Graph()
        Gi.add_nodes_from(vivos)
        Gi.add_edges_from(e for e, ok in zip(aristas, sel)
                          if ok and e[0] in vivos and e[1] in vivos)
        if Gi.number_of_nodes() > 0:
            cc = max(nx.connected_components(Gi), key=len)
            Gi = Gi.subgraph(cc).copy()
        grados = np.array([d for _, d in Gi.degree()], dtype=int)
        hist_s.append(np.bincount(grados, minlength=nmax)[:nmax])   # EN[k] = nº de nodos de grado k
        n_s.append(Gi.number_of_nodes())
        m_s.append(Gi.number_of_edges())
        gl_s.append(contar_graphlets(Gi, cat))
        if guardar_muestras:
            GS.append(Gi)

    hist = np.array(hist_s, dtype=float)
    gl = np.array(gl_s, dtype=float)
    res = {
        "cat": cat, "S": S,
        "En": float(np.mean(n_s)), "sn": float(np.std(n_s)),
        "Em": float(np.mean(m_s)), "sm": float(np.std(m_s)),
        "EN": hist.mean(axis=0), "sN": hist.std(axis=0),
        "frec_grado": (hist > 0).mean(axis=0), "hist": hist,
        "Ec": gl.mean(axis=0), "sc": gl.std(axis=0),
        "GS": GS,
    }
    # CCg = 3T / (W + 3T), con W = cuñas abiertas (M1) y T = triángulos (M2), medias de las muestras
    W, T = res["Ec"][0], res["Ec"][1]
    res["CCg"] = float(3 * T / (W + 3 * T)) if (W + 3 * T) > 0 else 0.0
    return res


