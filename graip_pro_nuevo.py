# 5. ALGORITHM 1: AddNode & GraphGenerator
# =====================================================================
def AddNode(H, CCg, u):
    """
    Devuelve la lista de aristas Eu del nuevo nodo u (no modifica H).
    v se elige con probabilidad proporcional a su grado y SIEMPRE queda conectado a u.
    """
    nodos = list(H.nodes())
    if not nodos:
        return []
    grados = np.array([H.degree(x) for x in nodos], dtype=float)
    if grados.sum() > 0:
        v = nodos[np.random.choice(len(nodos), p=grados / grados.sum())]
    else:
        v = random.choice(nodos)

    vecinos = list(H.adj[v])
    vecindad = H.subgraph([v] + vecinos)
    cliques = [c for c in nx.find_cliques(vecindad) if v in c and len(c) >= 4]
    if cliques:
        clique = max(cliques, key=len)
        return [(u, c) for c in clique]            # incluye la arista (u, v)

    Eu = [(u, v)]
    kv = len(vecinos)
    if kv > 0:
        env = H.subgraph(vecinos).number_of_edges()
        pnb = (kv + 1) * CCg / 2.0 - env / kv      # Algorithm 1, línea 47 (Ec. 7)
        pnb = min(1.0, max(0.0, pnb))
        for nv in vecinos:
            if random.random() < pnb:
                Eu.append((u, nv))
    return Eu


def _logistica(x):
    x = max(-60.0, min(60.0, x))
    return 1.0 / (1.0 + math.exp(-x))


def _f_logistica(valor, media, desv):
    """f = 1/(1+exp(-(valor-media)/desv)); si desv = 0 se usa el límite (0, 1/2 o 1)."""
    if desv > 0:
        return _logistica((valor - media) / desv)
    return 0.0 if valor < media else (1.0 if valor > media else 0.5)


def dentro_de_limites(PH, CH, Ep, sp, Ec, sc, K, tol=1e-3):
    PH = np.asarray(PH, dtype=float)
    CH = np.asarray(CH, dtype=float)
    return bool(np.all(PH >= Ep - K * sp - tol) and np.all(PH <= Ep + K * sp + tol) and
                np.all(CH >= Ec - K * sc - tol) and np.all(CH <= Ec + K * sc + tol))


def GraphGenerator(SAMPLE, ng=None, maxs=10000, node_step=5, w=2/3, maxrej=None, K=2,
                   seed=None, verbose=1000):
    """
    Algorithm 1: generador incremental GRAIP.
    SAMPLE: resultado de Sample(G, S, ng).  K = 2 corresponde al intervalo [E-2s, E+2s] del paper.
    """
    cat = SAMPLE["cat"]
    if ng is not None and ng != cat["ng"]:
        raise ValueError("ng no coincide con el usado en Sample")
    if seed is not None:
        random.seed(seed)
        np.random.seed(seed)

    En, sn, Em, sm = SAMPLE["En"], SAMPLE["sn"], SAMPLE["Em"], SAMPLE["sm"]
    Ec = np.asarray(SAMPLE["Ec"], dtype=float)
    sc = np.asarray(SAMPLE["sc"], dtype=float)
    CCg = SAMPLE["CCg"]
    bins, Ep, sp = objetivos_grado(SAMPLE)
    if maxrej is None:
        maxrej = max(10, int(round(0.02 * Em)))

    # Semilla: grafo BA con ~20% de los nodos y de las aristas.
    # OJO: el parámetro m de barabasi_albert_graph es "aristas por nodo nuevo", no el total.
    n0 = max(3, int(round(En / 5)))
    m0 = max(1, int(round(Em / 5)))
    m_ba = max(1, min(n0 - 1, int(round(m0 / n0))))
    H = nx.barabasi_albert_graph(n0, m_ba, seed=seed)
    proximo_id = n0

    def proporciones(Gr):
        return Histogram([d for _, d in Gr.degree()], bins) / max(Gr.number_of_nodes(), 1)

    PH = proporciones(H)
    CH = contar_graphlets(H, cat)
    costH = Cost(PH, CH, Ep, sp, Ec, sc, w, En)
    rechazos = 0

    history = {
        'steps': [], 'CH_trajectory': [], 'PG_hist_trajectory': [],
        'n_trajectory': [], 'm_trajectory': [], 'cost_trajectory': [],
        'Ep': Ep, 'sp': sp, 'Ec': Ec, 'sc': sc, 'bins': bins, 'K': K,
        'nombres': cat['nombres'], 'exito': False,
    }

    def registrar(paso):
        history['steps'].append(paso)
        history['CH_trajectory'].append(CH.tolist())
        history['PG_hist_trajectory'].append(PH.tolist())
        history['n_trajectory'].append(H.number_of_nodes())
        history['m_trajectory'].append(H.number_of_edges())
        history['cost_trajectory'].append(costH)

    for step in range(1, maxs + 1):
        registrar(step)
        if dentro_de_limites(PH, CH, Ep, sp, Ec, sc, K):
            history['exito'] = True
            print(f'ÉXITO en el paso {step}: n={H.number_of_nodes()}, m={H.number_of_edges()}')
            return H, history

        n = H.number_of_nodes()
        m = H.number_of_edges()
        r = random.random()
        accion = None
        if step % node_step == 0:
            if r > _f_logistica(n, En, sn):                       # agregar nodo
                accion = ("add_node", (proximo_id, AddNode(H, CCg, proximo_id)))
            elif n > 3:                                           # quitar nodo
                u = random.choice(list(H.nodes()))
                accion = ("remove_node", (u, list(H.adj[u])))
        else:
            m_escalado = m * En / n if n > 0 else 0.0             # m escalado por En/n (paper)
            if r > _f_logistica(m_escalado, Em, sm):              # agregar arista
                par = arista_ausente_al_azar(H)
                if par is not None:
                    accion = ("add_edge", par)
            elif m > 0:                                           # quitar arista
                accion = ("remove_edge", random.choice(list(H.edges())))
        if accion is None:
            continue

        dC = aplicar_cambio(H, accion, cat)
        CT = CH + dC
        PT = proporciones(H)
        costT = Cost(PT, CT, Ep, sp, Ec, sc, w, En)

        if costT < costH or rechazos >= maxrej:
            CH, PH, costH = CT, PT, costT
            rechazos = 0
            if accion[0] == "add_node":
                proximo_id += 1
        else:
            deshacer_cambio(H, accion)
            rechazos += 1

        if verbose and step % verbose == 0:
            print(f'paso {step}: n={H.number_of_nodes()}, m={H.number_of_edges()}, costo={costH:.4f}')

    registrar(maxs + 1)
    print(f'No convergió en {maxs} pasos (costo final {costH:.4f}).')
    return H, history

