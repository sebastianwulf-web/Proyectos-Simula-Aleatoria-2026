# 1. ACTUALIZACIÓN INCREMENTAL DE CONTEOS (aplicar / deshacer cambios)
# =====================================================================
def _delta_arista(H, u, v, cat, signo):
    """
    H debe CONTENER la arista (u,v). Devuelve signo * (conteos con (u,v) - conteos sin (u,v)).
    Sólo cambian los subgrafos que contienen a u y a v.
    """
    d = np.zeros(cat["n_tipos"], dtype=np.int64)
    for conj in conjuntos_conexos(H, {u, v}, cat["ng"]):
        if len(conj) < 3:
            continue
        nodos = [u, v] + [x for x in conj if x != u and x != v]
        k = len(nodos)
        m_con = mascara(H, nodos, cat)
        m_sin = m_con & ~1  # el par (0,1) = (u,v) es el bit 0
        i_con = cat["tabla"][(k, m_con)]
        i_sin = cat["tabla"][(k, m_sin)]
        if i_con >= 0:
            d[i_con] += signo
        if i_sin >= 0:
            d[i_sin] -= signo
    return d


def _delta_nodo(H, u, cat, signo):
    """H debe CONTENER el nodo u. Devuelve signo * (graphlets que contienen a u)."""
    d = np.zeros(cat["n_tipos"], dtype=np.int64)
    for conj in conjuntos_conexos(H, {u}, cat["ng"]):
        if len(conj) >= 3:
            nodos = list(conj)
            d[cat["tabla"][(len(nodos), mascara(H, nodos, cat))]] += signo
    return d


def aplicar_cambio(H, accion, cat):
    """Aplica el cambio sobre H (in place) y devuelve la variación de los conteos de graphlets."""
    tipo, datos = accion
    if tipo == "add_edge":
        u, v = datos
        H.add_edge(u, v)
        return _delta_arista(H, u, v, cat, +1)
    if tipo == "remove_edge":
        u, v = datos
        d = _delta_arista(H, u, v, cat, -1)
        H.remove_edge(u, v)
        return d
    if tipo == "add_node":
        u, Eu = datos
        H.add_node(u)
        H.add_edges_from(Eu)
        return _delta_nodo(H, u, cat, +1)
    if tipo == "remove_node":
        u = datos[0]
        d = _delta_nodo(H, u, cat, -1)
        H.remove_node(u)
        return d
    raise ValueError(tipo)


def deshacer_cambio(H, accion):
    """Revierte un cambio hecho con aplicar_cambio (evita copiar H en cada paso)."""
    tipo, datos = accion
    if tipo == "add_edge":
        H.remove_edge(*datos)
    elif tipo == "remove_edge":
        H.add_edge(*datos)
    elif tipo == "add_node":
        H.remove_node(datos[0])
    elif tipo == "remove_node":
        u, vecinos = datos
        H.add_node(u)
        H.add_edges_from((u, x) for x in vecinos)


def arista_ausente_al_azar(H, intentos=200):
    nodos = list(H.nodes())
    if len(nodos) < 2:
        return None
    for _ in range(intentos):
        a, b = random.sample(nodos, 2)
        if not H.has_edge(a, b):
            return (a, b)
    return None


