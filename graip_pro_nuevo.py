# 2. ALGORITHM 2: Cost function
# =====================================================================
def Cost(PG, CG, Ep, sp, Ec, sc, w, En=None):
    """
    Algorithm 2.
    costp: desviación relativa media de la distribución de grados ACUMULADA (desde arriba).
    costc: para cada graphlet fuera de [Ec-2sc, Ec+2sc] suma log_{1-f}(CG/Ec) o log_{1+f}(CG/Ec),
           con f = 2sc/Ec, dividido por |Ec|.
    """
    PG = np.asarray(PG, dtype=float)
    Ep = np.asarray(Ep, dtype=float)
    pc_g = np.cumsum(PG[::-1])[::-1]
    ec_p = np.cumsum(Ep[::-1])[::-1]
    piso = (1.0 / En) if En else 1e-8          # evita dividir por 0 en bins de peso 0
    costp = np.sum(np.abs(pc_g - ec_p) / np.maximum(ec_p, piso)) / len(Ep)

    costc = 0.0
    nc = len(Ec)
    for i in range(nc):
        E, s, c = float(Ec[i]), float(sc[i]), float(CG[i])
        if E <= 0:
            # Caso no definido en el paper (Ec = 0): se penaliza cualquier aparición.
            if c > 0:
                costc += math.log1p(c) / nc
            continue
        f = 2.0 * s / E
        if c < E - 2 * s:                          # aquí siempre f < 1
            f = min(max(f, 1e-3), 0.999)
            r = max(c, 0.5) / E                    # evita log(0)
            costc += (math.log(r) / math.log(1.0 - f)) / nc
        elif c > E + 2 * s:
            f = max(f, 1e-3)
            costc += (math.log(c / E) / math.log(1.0 + f)) / nc
    return w * costp + (1 - w) * costc


