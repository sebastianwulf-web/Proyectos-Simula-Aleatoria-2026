def AddNode_dirigido(H, CCg, u):
    """
    Devuelve la lista de arcos dirigidos Eu del nuevo nodo u (no modifica H).
    v se elige proporcionalmente a su grado total y se conecta con u.
    """
    nodos = list(H.nodes())
    if not nodos:
        return []

    # Grado total en DiGraph (in_degree + out_degree)
    grados = np.array([H.degree(x) for x in nodos], dtype=float)
    if grados.sum() > 0:
        v = nodos[np.random.choice(len(nodos), p=grados / grados.sum())]
    else:
        v = random.choice(nodos)

    # Vecindario débil en grafos dirigidos (unión de predecesores y sucesores)
    vecinos = list(set(H.successors(v)) | set(H.predecessors(v)))

    # Para la búsqueda de cliques locales, usamos temporalmente el grafo subyacente no dirigido
    H_und = H.to_undirected()
    vecindad = H_und.subgraph([v] + vecinos)
    cliques = [c for c in nx.find_cliques(vecindad) if v in c and len(c) >= 4]

    if cliques:
        clique = max(cliques, key=len)
        return [(u, c) for c in clique if c != u]  # Arcos dirigidos desde u hacia la clique

    Eu = [(u, v)]
    kv = len(vecinos)
    if kv > 0:
        # Corrección de la fórmula original de densidad local con sintaxis limpia
        env = H_und.subgraph(vecinos).number_of_edges()
        pnb = (kv + 1) * CCg / (2.0 * max(env, 1) / max(kv, 1)) if env > 0 else 0.0
        pnb = min(1.0, max(0.0, pnb))

        for nv in vecinos:
            if random.random() < pnb:
                Eu.append((u, nv))

    return Eu

def _logistica(x):
    x = max(-60.0, min(60.0, x))
    return 1.0 / (1.0 + math.exp(-x))


def _f_logistica(valor, media, desv):
    """f = 1/(1+exp(-(valor-media)/desv)); si desv = 0 se usa el límite (0, 1/2 o 1)."""
    if desv > 0:
        return _logistica((valor - media) / desv)
    return 0.0 if valor < media else (1.0 if valor > media else 0.5)


def dentro_de_limites(PH, CH, Ep, sp, Ec, sc, K, tol=1e-9):
    PH = np.asarray(PH, dtype=float)
    CH_v=np.array(list(CH.values()))
    Ec_v=np.array(list(Ec.values()))
    sc_v=np.array(list(sc.values()))
    return bool(np.all(PH >= Ep - K * sp - tol) and np.all(PH <= Ep + K * sp + tol) and
                np.all(CH_v >= Ec_v - K * sc_v - tol) and np.all(CH_v <= Ec_v + K * sc_v + tol))


def GraphGenerator_dirigido(SAMPLE, ng=None, maxs=10000, node_step=5, w=2/3, maxrej=None, K=2,
                            seed=None, verbose=1000,indexes=None):
    """
    Algoritmo 1: generador incremental GRAIP adaptado para grafos dirigidos (DiGraph).
    SAMPLE: resultado de Sample_dirigido(G, S, ng). K = 2 corresponde al intervalo [E-2s, E+2s].
    """
    cat = SAMPLE["cat"]
    if ng is not None and ng != cat["ng"]:
        raise ValueError("ng no coincide con el usado en Sample")
    if seed is not None:
        random.seed(seed)
        np.random.seed(seed)

    En, sn, Em, sm = SAMPLE["En"], SAMPLE["sn"], SAMPLE["Em"], SAMPLE["sm"]
    Ec = SAMPLE["Ec"]
    sc = SAMPLE["sc"]
    CCg = SAMPLE["CCg"]

    if indexes is not None:
      Ec={i:Ec[i] for i in range(len(Ec)) if i in indexes}
      sc={i:sc[i] for i in range(len(sc)) if i in indexes}

    bins, Ep, sp = objetivos_grado(SAMPLE)
    if maxrej is None:
        maxrej = max(10, int(round(0.02 * Em)))

    # Semilla: grafo BA convertido a DiGraph (con arcos dirigidos)
    n0 = max(3, int(round(En / 5)))
    m0 = max(1, int(round(Em / 5)))
    m_ba = max(1, min(n0 - 1, int(round(m0 / n0))))
    H = nx.DiGraph(nx.barabasi_albert_graph(n0, m_ba, seed=seed))
    proximo_id = n0

    def proporciones(Gr):
        # En grafos dirigidos, usamos el grado total (in_degree + out_degree) para el histograma de grados
        return Histogram([d for _, d in Gr.degree()], bins) / max(Gr.number_of_nodes(), 1)

    PH = proporciones(H)
    CH = contar_graphlets_dirigidos(H, cat)
    costH = Cost(PH, CH, Ep, sp, Ec, sc, w, En)
    rechazos = 0

    history = {
        'steps': [], 'CH_trajectory': [], 'PG_hist_trajectory': [],
        'n_trajectory': [], 'm_trajectory': [], 'cost_trajectory': [],
        'Ep': Ep, 'sp': sp, 'Ec': Ec, 'sc': sc, 'bins': bins, 'K': K,
        'nombres': cat['nombres'], 'exito': False,
    }

    def registrar(paso):
        history['steps'].append(paso)
        history['CH_trajectory'].append(CH)
        history['PG_hist_trajectory'].append(PH.tolist())
        history['n_trajectory'].append(H.number_of_nodes())
        history['m_trajectory'].append(H.number_of_edges())
        history['cost_trajectory'].append(costH)

    for step in range(1, maxs + 1):
        registrar(step)
        if dentro_de_limites(PH, CH, Ep, sp, Ec, sc, K):
            history['exito'] = True
            print(f'ÉXITO en el paso {step}: n={H.number_of_nodes()}, m={H.number_of_edges()}')
            return H, history

        n = H.number_of_nodes()
        m = H.number_of_edges()
        r = random.random()
        accion = None

        if step % node_step == 0:
            if r > _f_logistica(n, En, sn):                      # agregar nodo con arcos dirigidos
                accion = ("add_node", (proximo_id, AddNode_dirigido(H, CCg, proximo_id)))
            elif n > 3:                                         # quitar nodo (guardando arcos entrantes y salientes)
                u = random.choice(list(H.nodes()))
                arcos_conectados = list(H.in_edges(u)) + list(H.out_edges(u))
                accion = ("remove_node", (u, arcos_conectados))
        else:
            m_escalado = m * En / n if n > 0 else 0.0             # m escalado por En/n
            if r > _f_logistica(m_escalado, Em, sm):              # agregar arco dirigido ausente
                par = arco_ausente_al_azar(H)
                if par is not None:
                    accion = ("add_edge", par)
            elif m > 0:                                         # quitar arco dirigido existente
                accion = ("remove_edge", random.choice(list(H.edges())))

        if accion is None:
            continue

        dC = aplicar_cambio_dirigido(H, accion, cat)
        if indexes is not None:CT = {i:CH[i]+dC[i] for i in indexes}
        else:CT={i:CH[i]+dC[i] for i in range(len(CH))}
        PT = proporciones(H)
        costT = Cost(PT, CT, Ep, sp, Ec, sc, w, En)

        if costT < costH or rechazos >= maxrej:
            CH, PH, costH = CT, PT, costT
            rechazos = 0
            if accion[0] == "add_node":
                proximo_id += 1
        else:
            deshacer_cambio_dirigido(H, accion)
            rechazos += 1

        if verbose and step % verbose == 0:
            print(f'paso {step}: n={H.number_of_nodes()}, m={H.number_of_edges()}, costo={costH:.4f}')

    registrar(maxs + 1)
    print(f'No convergió en {maxs} pasos (costo final {costH:.4f}).')
    return H, history

