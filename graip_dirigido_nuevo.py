def _delta_arista_dirigida(H, u, v, cat, signo, indexes=None):
    """
    H debe CONTENER el arco dirigido (u,v). Devuelve signo * (conteos con (u,v) - conteos sin (u,v)).
    Si se pasa 'indexes', devuelve un dict {idx: delta} solo para esos graphlets.
    """
    d = np.zeros(cat["n_tipos"], dtype=np.int64)

    for conj in conjuntos_conexos_dirigidos(H, {u, v}, cat["ng"]):
        if len(conj) < 3:
            continue

        nodos = [u, v] + [x for x in conj if x != u and x != v]
        k = len(nodos)

        m_con = mascara_dirigida(H, nodos, cat)

        bit_idx = -1
        pares_k = cat["pares"][k]
        par_buscado = (0, 1)
        if par_buscado in pares_k:
            bit_idx = pares_k.index(par_buscado)

        if bit_idx != -1:
            m_sin = m_con & ~(1 << bit_idx)
        else:
            m_sin = m_con

        i_con = cat["tabla"][(k, m_con)]
        i_sin = cat["tabla"][(k, m_sin)]

        if i_con >= 0:
            d[i_con] += signo
        if i_sin >= 0:
            d[i_sin] -= signo

    # Si se especifican índices, filtramos y devolvemos un diccionario
    if indexes is not None:
        return {int(idx): int(d[idx]) for idx in indexes if 0 <= idx < cat["n_tipos"] and d[idx] != 0}
    else:
        return dict(enumerate(d))


def _delta_nodo_dirigido(H, u, cat, signo, indexes=None):
    """
    H debe CONTENER el nodo u. Devuelve signo * (graphlets dirigidos que contienen a u).
    Si se pasa 'indexes', devuelve un dict {idx: delta} solo para esos graphlets.
    """
    d = np.zeros(cat["n_tipos"], dtype=np.int64)
    for conj in conjuntos_conexos_dirigidos(H, {u}, cat["ng"]):
        if len(conj) >= 3:
            nodos = list(conj)
            idx = cat["tabla"][(len(nodos), mascara_dirigida(H, nodos, cat))]
            if idx >= 0:
                d[idx] += signo

    if indexes is not None:
        return {int(idx): int(d[idx]) for idx in indexes if 0 <= idx < cat["n_tipos"] and d[idx] != 0}
    else:
        return dict(enumerate(d))


def aplicar_cambio_dirigido(H, accion, cat, indexes=None):
    """
    Aplica el cambio sobre el DiGraph H (in place) y devuelve la variación
    de los conteos (en formato diccionario si 'indexes' está presente, o array NumPy).
    """
    tipo, datos = accion

    if tipo == "add_edge":
        u, v = datos
        H.add_edge(u, v)
        return _delta_arista_dirigida(H, u, v, cat, +1, indexes=indexes)

    elif tipo == "remove_edge":
        u, v = datos
        d = _delta_arista_dirigida(H, u, v, cat, -1, indexes=indexes)
        H.remove_edge(u, v)
        return d

    elif tipo == "add_node":
        u, Eu = datos
        H.add_node(u)
        H.add_edges_from(Eu)
        return _delta_nodo_dirigido(H, u, cat, +1, indexes=indexes)

    elif tipo == "remove_node":
        u = datos[0]
        d = _delta_nodo_dirigido(H, u, cat, -1, indexes=indexes)
        H.remove_node(u)
        return d

    raise ValueError(f"Tipo de acción no reconocido: {tipo}")


def deshacer_cambio_dirigido(H, accion):
    """Revierte un cambio hecho con aplicar_cambio_dirigido en un DiGraph (sin cambios)."""
    tipo, datos = accion

    if tipo == "add_edge":
        H.remove_edge(*datos)
    elif tipo == "remove_edge":
        H.add_edge(*datos)
    elif tipo == "add_node":
        H.remove_node(datos[0])
    elif tipo == "remove_node":
        u, arcos = datos
        H.add_node(u)
        H.add_edges_from(arcos)


def arco_ausente_al_azar(H, intentos=200):
    """Busca un arco dirigido (a -> b) que NO exista actualmente en el DiGraph."""
    nodos = list(H.nodes())
    if len(nodos) < 2:
        return None
    for _ in range(intentos):
        a, b = random.sample(nodos, 2)
        if not H.has_edge(a, b):
            return (a, b)
    return None


