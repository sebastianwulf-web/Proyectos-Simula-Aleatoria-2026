# 3. ALGORITHM 3: Bin degree histogram
# =====================================================================
def BinDegrees(EN, S, frecuencia=None, umbral=0.01):
    """
    Algorithm 3. Recorre los grados desde el mayor hacia 1 y cierra un bin cuando
    su peso (suma de EN) llega a 1, o cuando termina un tramo de grados que no aparecen.
    Ajuste de colas: los grados que aparecen en menos del 1% de las muestras
    se tratan como peso 0 (quedan en bins de peso cero).
    Devuelve bordes izquierdos [b0, b1, ..., bk] (bin i = [b_i, b_{i+1})) desde grado 1.
    """
    EN = np.array(EN, dtype=float)
    if frecuencia is not None:
        EN[np.asarray(frecuencia) < umbral] = 0.0
    nz = np.nonzero(EN[1:])[0]
    kmax = int(nz.max()) + 1 if len(nz) else 1
    bin_edge = kmax + 1
    bins = [bin_edge]
    weights = []
    zero_bin = False
    w = 0.0
    while bin_edge > 1:
        bin_edge -= 1
        w += EN[bin_edge]
        if bin_edge == 1 or w >= 1 or (zero_bin and EN[bin_edge - 1] != 0):
            bins.append(bin_edge)
            weights.append(w)
            w = 0.0
            zero_bin = bool(EN[bin_edge - 1] == 0)
    return bins[::-1], weights[::-1]


def Histogram(datos, bins):
    """Cuenta cuántos valores caen en cada bin [bins[i], bins[i+1]) (último borde puede ser inf)."""
    bins = np.asarray(bins, dtype=float)
    datos = np.asarray(datos, dtype=float)
    idx = np.searchsorted(bins, datos, side="right") - 1
    ok = (idx >= 0) & (idx < len(bins) - 1)
    return np.bincount(idx[ok], minlength=len(bins) - 1).astype(float)


def objetivos_grado(muestra):
    """
    Construye los bins y los objetivos Ep ± K·sp de la distribución de grados.
    Se agregan un bin [0,1) (grado 0) y un bin de desborde [kmax+1, inf) con peso 0,
    para que un grado mayor que cualquiera observado SÍ sea penalizado.
    """
    EN = np.asarray(muestra["EN"], dtype=float)
    hist = muestra["hist"]
    En = muestra["En"]
    b, wts = BinDegrees(EN, muestra["S"], muestra["frec_grado"])
    bins = [0] + list(b) + [np.inf]
    weights = [float(EN[0])] + list(wts) + [0.0]
    sN = []
    for i in range(len(bins) - 1):
        a, c = bins[i], bins[i + 1]
        if np.isinf(c):
            sN.append(0.0)
        elif c - a == 1:
            sN.append(float(np.std(hist[:, int(a)])))          # bin de ancho 1: desviación muestral
        else:
            wv = weights[i]                                     # bin ancho: [w-2s, w+2s] contiene floor y ceil
            sN.append(max(wv - math.floor(wv), math.ceil(wv) - wv) / 2.0)
    Ep = np.array(weights) / En
    sp = np.array(sN) / En
    return bins, Ep, sp


