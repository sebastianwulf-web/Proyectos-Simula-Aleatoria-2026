# 4. FUNCIÓN SAMPLE (Monte Carlo sobre la red probabilística)
# =====================================================================
def Sample_dirigido(G, S, ng=3, seed=None, guardar_muestras=False):
    """
    Genera S grafos dirigidos posibles de G (con probabilidades en nodos/arcos),
    toma la COMPONENTE DÉBILMENTE CONEXA MAYOR de cada muestra y calcula
    las estadísticas, histogramas y graphlets dirigidos (manejando diccionarios).
    """
    rng = np.random.default_rng(seed)
    cat = catalogo_graphlets_dirigidos(ng)

    nodos = list(G.nodes())
    aristas = list(G.edges())
    p_nodo = np.array([G.nodes[x].get("prob", 1.0) for x in nodos], dtype=float)
    p_arista = np.array([G[a][b].get("prob", 1.0) for a, b in aristas], dtype=float)
    nmax = len(nodos)

    n_s, m_s, hist_s, gl_s, GS = [], [], [], [], []

    for _ in range(S):
        vivo = rng.random(nmax) < p_nodo
        vivos = {x for x, ok in zip(nodos, vivo) if ok}
        sel = rng.random(len(aristas)) < p_arista

        Gi = nx.DiGraph()
        Gi.add_nodes_from(vivos)
        Gi.add_edges_from(e for e, ok in zip(aristas, sel)
                          if ok and e[0] in vivos and e[1] in vivos)

        if Gi.number_of_nodes() > 0:
            cc = max(nx.weakly_connected_components(Gi), key=len)
            Gi = Gi.subgraph(cc).copy()

        grados = np.array([d for _, d in Gi.degree()], dtype=int)

        if len(grados) > 0:
            hist_s.append(np.bincount(grados, minlength=nmax)[:nmax])
        else:
            hist_s.append(np.zeros(nmax, dtype=int))

        n_s.append(Gi.number_of_nodes())
        m_s.append(Gi.number_of_edges())

        # contar_graphlets_dirigidos ya devuelve un dict {idx: frecuencia}
        gc = contar_graphlets_dirigidos(Gi, cat)
        gl_s.append(gc)

        if guardar_muestras:
            GS.append(Gi)

    hist = np.array(hist_s, dtype=float)

    # Procesar Ec y sc manteniendo la estructura de diccionarios por índice
    n_tipos = cat["n_tipos"]
    Ec_dict = {}
    sc_dict = {}

    for idx in range(n_tipos):
        valores = [sample.get(idx, 0.0) for sample in gl_s]
        Ec_dict[idx] = float(np.mean(valores))
        sc_dict[idx] = float(np.std(valores))

    res = {
        "cat": cat, "S": S,
        "En": float(np.mean(n_s)), "sn": float(np.std(n_s)),
        "Em": float(np.mean(m_s)), "sm": float(np.std(m_s)),
        "EN": hist.mean(axis=0), "sN": hist.std(axis=0),
        "frec_grado": (hist > 0).mean(axis=0), "hist": hist,
        "Ec": Ec_dict,  # Diccionario {idx: promedio}
        "sc": sc_dict,  # Diccionario {idx: desviacion}
        "GS": GS,
    }

    # Cálculo seguro de CCg compatible con diccionarios
    try:
        idx_c3 = cat["nombres"].index("Ciclo dirigido de 3 (C3)")
        T = res["Ec"].get(idx_c3, 0.0)
    except ValueError:
        T = res["Ec"].get(2, 0.0)

    W = res["Ec"].get(0, 0.0)

    res["CCg"] = float(3 * T / (W + 3 * T)) if (W + 3 * T) > 0 else 0.0

    return res

