def catalogo_graphlets_dirigidos(ng):
    """
    Construye el catálogo de graphlets dirigidos de 3..ng nodos.
    Utiliza _NOMBRES_3_DIRIGIDOS para k=3 y nombres genéricos para k > 3.
    """
    pares = {k: list(itertools.permutations(range(k), 2)) for k in range(2, ng + 1)}
    tabla = {}
    nombres = []
    ordenes = []
    total = 0

    for k in range(3, ng + 1):
        P = pares[k]
        reps_k = []
        mascaras = sorted(range(1 << len(P)), key=lambda x: (bin(x).count("1"), x))

        for mask in mascaras:
            g = nx.DiGraph()
            g.add_nodes_from(range(k))
            g.add_edges_from(P[b] for b in range(len(P)) if (mask >> b) & 1)

            if not nx.is_weakly_connected(g):
                tabla[(k, mask)] = -1
                continue

            idx = -1
            for j, rep in reps_k:
                if rep.number_of_edges() == g.number_of_edges() and nx.is_isomorphic(rep, g):
                    idx = j
                    break

            if idx == -1:
                idx = total
                total += 1
                reps_k.append((idx, g))
                ordenes.append(k)

                num_arcos = g.number_of_edges()
                if k == 3:
                    # Extraemos la firma de grados (in, out) ordenada para buscar en el diccionario
                    grados_in_out = tuple(sorted((g.in_node_degree(n) if hasattr(g, 'in_node_degree') else g.in_degree(n),
                                                 g.out_degree(n)) for n in g.nodes()))
                    firma = (num_arcos, grados_in_out)
                    nombre = _NOMBRES_3_DIRIGIDOS.get(firma, f"Graphlet k=3, {num_arcos} arcos (Desconocido)")
                else:
                    nombre = f"{k} nodos, {num_arcos} arcos"
                nombres.append(nombre)

            tabla[(k, mask)] = idx

    return {
        "ng": ng,
        "pares": pares,
        "tabla": tabla,
        "nombres": nombres,
        "ordenes": ordenes,
        "n_tipos": total
    }


def mascara_dirigida(G, nodos, cat):
    """Máscara de bits del subgrafo dirigido inducido por 'nodos' (en ese orden)."""
    k = len(nodos)
    m = 0
    for b, (i, j) in enumerate(cat["pares"][k]):
        if G.has_edge(nodos[i], nodos[j]):
            m |= 1 << b
    return m


def conjuntos_conexos_dirigidos(G, semilla, kmax, permitido=None):
    """
    Todos los conjuntos de nodos que inducen un subgrafo débilmente conexo en G, de tamaño <= kmax,
    conteniendo a la semilla. Explora mediante sucesores y predecesores (grafo subyacente).
    """
    inicio = frozenset(semilla)
    vistos = {inicio}
    frontera = [inicio]

    while frontera:
        siguiente = []
        for C in frontera:
            if len(C) >= kmax:
                continue
            vecinos = set()
            for x in C:
                vecinos.update(G.successors(x))
                vecinos.update(G.predecessors(x))
            vecinos -= C

            for y in vecinos:
                if permitido is not None and not permitido(y):
                    continue
                D = C | {y}
                if D not in vistos:
                    vistos.add(D)
                    siguiente.append(D)
        frontera = siguiente
    return vistos


def contar_graphlets_dirigidos(G, cat, indexes=None):
    """
    Conteo exacto de graphlets dirigidos de 3..ng nodos.
    Si 'indexes' es provisto (ej. lista o tupla de índices), devuelve un diccionario
    con {idx: frecuencia} solo para esos índices. De lo contrario, devuelve el array completo C.
    """
    C = np.zeros(cat["n_tipos"], dtype=np.int64)
    rango = {v: i for i, v in enumerate(G.nodes())}

    for v in G.nodes():
        rv = rango[v]
        for conj in conjuntos_conexos_dirigidos(G, {v}, cat["ng"], permitido=lambda y: rango[y] > rv):
            if len(conj) >= 3:
                idx = cat["tabla"][(len(conj), mascara_dirigida(G, list(conj), cat))]
                if idx >= 0:
                    C[idx] += 1

    # Si se especifican índices, filtramos y construimos el diccionario
    if indexes is not None:
        return {int(idx): int(C[idx]) for idx in indexes if 0 <= idx < cat["n_tipos"]}
    else:
        return dict(enumerate(C))


def contar_graphlets_fuerza_bruta_dirigidos(G, cat, indexes=None):
    """
    Conteo por fuerza bruta para grafos dirigidos.
    Si 'indexes' es provisto, devuelve un diccionario {idx: frecuencia}.
    """
    C = np.zeros(cat["n_tipos"], dtype=np.int64)
    for k in range(3, cat["ng"] + 1):
        for comb in itertools.combinations(G.nodes(), k):
            idx = cat["tabla"][(k, mascara_dirigida(G, list(comb), cat))]
            if idx >= 0:
                C[idx] += 1

    if indexes is not None:
        return {int(idx): int(C[idx]) for idx in indexes if 0 <= idx < cat["n_tipos"]}
    else:
        return dict(enumerate(C))

