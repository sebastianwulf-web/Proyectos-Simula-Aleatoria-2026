def plot_parameters_evolution(history, indexes=None):
    """
    Muestra la evolución de los graphlets y grados a lo largo de las iteraciones.
    Soporta trayectorias y objetivos guardados como diccionarios o arrays.
    """
    steps = history['steps']

    # 1. Manejar CH_trajectory si viene como lista de diccionarios
    ch_traj_raw = history['CH_trajectory']
    if len(ch_traj_raw) > 0 and isinstance(ch_traj_raw[0], dict):
        n_steps = len(ch_traj_raw)
        max_idx = max(max(d.keys()) for d in ch_traj_raw if d) if ch_traj_raw else 0
        n_cols = max_idx + 1
        ch_traj_full = np.zeros((n_steps, n_cols), dtype=float)
        for step_idx, d in enumerate(ch_traj_raw):
            for k, v in d.items():
                ch_traj_full[step_idx, k] = v
    else:
        ch_traj_full = np.array(ch_traj_raw, dtype=float)

    pg_traj = np.array(history['PG_hist_trajectory'], dtype=float)
    bins = history.get('bins')
    nombres = history.get('nombres', [])
    K = history.get('K', 2)

    n_cols = ch_traj_full.shape[1]
    Ec_full = history['Ec']
    sc_full = history['sc']

    # 2. Alineación segura de Ec y sc al tamaño exacto de columnas (n_cols)
    Ec_arr = np.zeros(n_cols, dtype=float)
    sc_arr = np.zeros(n_cols, dtype=float)

    if isinstance(Ec_full, dict):
        for k, v in Ec_full.items():
            if k < n_cols:
                Ec_arr[k] = v
    else:
        Ec_arr[:len(Ec_full)] = np.array(Ec_full, dtype=float)[:n_cols]

    if isinstance(sc_full, dict):
        for k, v in sc_full.items():
            if k < n_cols:
                sc_arr[k] = v
    else:
        sc_arr[:len(sc_full)] = np.array(sc_full, dtype=float)[:n_cols]

    Ec_full, sc_full = Ec_arr, sc_arr
    Ep, sp = np.array(history['Ep']), np.array(history['sp'])

    # 3. Filtrar por índices si se especifican
    if indexes is not None:
        validos = [idx for idx in indexes if idx < n_cols]
        ch_traj = ch_traj_full[:, validos]
        Ec = Ec_full[validos]
        sc = sc_full[validos]
        etiquetas_graphlets = [f"M{idx+1}: {nombres[idx] if idx < len(nombres) else f'Graphlet {idx+1}'}" for idx in validos]
    else:
        ch_traj = ch_traj_full
        Ec = Ec_full
        sc = sc_full
        etiquetas_graphlets = [f"M{i+1}: {nombres[i] if i < len(nombres) else f'Graphlet {i+1}'}" for i in range(n_cols)]

    fig, axes = plt.subplots(2, 1, figsize=(13, 11))

    # --- Gráfica superior: Graphlets ---
    ncol = ch_traj.shape[1]
    colores = plt.cm.tab20(np.linspace(0, 1, max(ncol, 2)))
    for i in range(ncol):
        axes[0].plot(steps, ch_traj[:, i], color=colores[i], lw=1.6, label=etiquetas_graphlets[i])
        axes[0].axhline(y=Ec[i], color=colores[i], linestyle='--', alpha=0.7)
        axes[0].fill_between(steps, Ec[i] - K * sc[i], Ec[i] + K * sc[i], color=colores[i], alpha=0.1)

    axes[0].set_title(rf'Evolución de los graphlets dirigidos ($C_H$) vs objetivo ($E_c \pm {K} s_c$)', fontsize=12, fontweight='bold')
    axes[0].set_ylabel('Conteo')
    axes[0].grid(True, linestyle='--', alpha=0.5)
    axes[0].legend(loc='upper left', fontsize=8, ncol=2)

    # --- Gráfica inferior: Distribución de Grados ---
    nb = pg_traj.shape[1]
    colores_pg = plt.cm.viridis(np.linspace(0, 1, max(nb, 2)))
    for i in range(nb):
        etiqueta = f"grados [{bins[i]}, {bins[i+1]})" if bins is not None else f"Bin {i+1}"
        axes[1].plot(steps, pg_traj[:, i], color=colores_pg[i], lw=1.4, label=etiqueta)
        axes[1].axhline(y=Ep[i], color=colores_pg[i], linestyle='--', alpha=0.5)
        axes[1].fill_between(steps, Ep[i] - K * sp[i], Ep[i] + K * sp[i], color=colores_pg[i], alpha=0.05)

    axes[1].set_ylim(0, 1.05)
    axes[1].set_title(rf'Evolución de los {nb} bins de la distribución de grados ($P_H$) vs objetivo ($E_p \pm {K} s_p$)', fontsize=12, fontweight='bold')
    axes[1].set_xlabel('Paso')
    axes[1].set_ylabel('Proporción de nodos')
    axes[1].grid(True, linestyle='--', alpha=0.5)
    axes[1].legend(loc='upper right', fontsize=8, ncol=2)

    plt.tight_layout()
    plt.show()


def plot_graphlet_bar_comparison(C_H, data_dict, ng=None, indexes=None):
    """
    Gráfico de barras: frecuencias de graphlets dirigidos vs objetivo Ec ± K·sc.
    Acepta C_H y data_dict tanto en formato array como en diccionario.
    Si se pasa 'indexes', solo grafica esos índices específicos.
    """
    K = data_dict.get("K", 2)
    nombres = list(data_dict.get("nombres", []))

    E_c_raw = data_dict.get("E_c", data_dict.get("Ec"))
    s_c_raw = data_dict.get("s_c", data_dict.get("sc"))

    # Si vienen como diccionarios, los convertimos o extraemos según indexes
    if isinstance(C_H, dict):
        if indexes is not None:
            indices_a_usar = indexes
            C_H_vals = [C_H.get(idx, 0.0) for idx in indexes]
            E_c_vals = [E_c_raw.get(idx, 0.0) for idx in indexes]
            s_c_vals = [s_c_raw.get(idx, 0.0) for idx in indexes]
        else:
            indices_a_usar = sorted(C_H.keys())
            C_H_vals = [C_H[idx] for idx in indices_a_usar]
            E_c_vals = [E_c_raw.get(idx, 0.0) for idx in indices_a_usar]
            s_c_vals = [s_c_raw.get(idx, 0.0) for idx in indices_a_usar]
    else:
        C_H_arr = np.array(C_H, dtype=float)
        E_c_arr = np.array(E_c_raw, dtype=float)
        s_c_arr = np.array(s_c_raw, dtype=float)

        if indexes is not None:
            indices_a_usar = indexes
            C_H_vals = C_H_arr[indexes]
            E_c_vals = E_c_arr[indexes]
            s_c_vals = s_c_arr[indexes]
        else:
            indices_a_usar = list(range(len(C_H_arr)))
            C_H_vals = C_H_arr
            E_c_vals = E_c_arr
            s_c_vals = s_c_arr

    num = len(indices_a_usar)
    etiquetas = [f"M{idx+1}: {nombres[idx] if idx < len(nombres) else f'Graphlet {idx+1}'}" for idx in indices_a_usar]

    x = np.arange(num)
    width = 0.38

    fig, ax = plt.subplots(figsize=(max(12, 0.7 * num), 6))
    ax.bar(x - width/2, C_H_vals, width, label='Grafo generado ($C_H$)', color='#2ca02c', edgecolor='black', alpha=0.85)
    ax.bar(x + width/2, E_c_vals, width, yerr=K * np.array(s_c_vals), capsize=5,
           label=rf'Objetivo ($E_c \pm {K} s_c$)', color='#1f77b4', edgecolor='black', alpha=0.85)

    ax.set_ylabel('Conteo', fontsize=11, fontweight='bold')
    ax.set_title('Comparación de frecuencias de graphlets dirigidos', fontsize=13, fontweight='bold')
    ax.set_xticks(x)
    ax.set_xticklabels(etiquetas, rotation=45, ha='right', fontsize=9)
    ax.legend(fontsize=10, loc='upper right')
    ax.grid(axis='y', linestyle='--', alpha=0.5)

    plt.tight_layout()
    plt.show()

